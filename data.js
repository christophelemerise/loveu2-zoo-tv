window.LOVEU2.fmt = function (iso, style) {
  var d = new Date(iso + 'T20:00:00');
  var M = ['January','February','March','April','May','June','July','August','September','October','November','December'];
  if (style === 'short') return M[d.getMonth()].slice(0, 3) + ' ' + d.getDate();
  if (style === 'parts') return { m: M[d.getMonth()].slice(0, 3), d: d.getDate(), y: d.getFullYear(), month: M[d.getMonth()] };
  return M[d.getMonth()] + ' ' + d.getDate() + ', ' + d.getFullYear();
};
